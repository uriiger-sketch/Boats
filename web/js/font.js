const Font = (() => {
  const GH = 7;
  const order = Object.keys(GLYPHS);
  const layout = {}; // char -> {x, w}
  let atlasW = 0;
  for (const ch of order) { const w = GLYPHS[ch][0].length; layout[ch] = { x: atlasW, w }; atlasW += w + 1; }
  const atlases = new Map();

  function atlas(color) {
    let a = atlases.get(color);
    if (a) return a;
    a = makeCanvas(atlasW, GH);
    const x = a.getContext('2d');
    x.fillStyle = color;
    for (const ch of order) {
      const g = GLYPHS[ch], l = layout[ch];
      for (let j = 0; j < GH; j++) for (let i = 0; i < l.w; i++) if (g[j][i] === '#') x.fillRect(l.x + i, j, 1, 1);
    }
    atlases.set(color, a);
    return a;
  }

  const norm = (ch) => (ch === '×' ? 'x' : layout[ch] ? ch : layout[ch.toUpperCase()] ? ch.toUpperCase() : ' ');

  function width(str, scale = 1) {
    let w = 0;
    for (const c of String(str)) w += layout[norm(c)].w + 1;
    return Math.max(0, w - 1) * scale;
  }

  function raw(ctx, str, x, y, color, scale) {
    const a = atlas(color);
    let cx = x;
    for (const c of String(str)) {
      const l = layout[norm(c)];
      ctx.drawImage(a, l.x, 0, l.w, GH, cx, y, l.w * scale, GH * scale);
      cx += (l.w + 1) * scale;
    }
  }

  // opts: scale, align ('left'|'center'|'right'), outline colour, shadow colour
  function draw(ctx, str, x, y, color = '#fff', opts = {}) {
    const s = opts.scale || 1;
    const w = width(str, s);
    let sx = x;
    if (opts.align === 'center') sx = x - Math.floor(w / 2);
    else if (opts.align === 'right') sx = x - w;
    sx = Math.round(sx); y = Math.round(y);
    const o = opts.outline;
    if (o) {
      const t = opts.thick || 1;
      for (const [dx, dy] of [[-t, 0], [t, 0], [0, -t], [0, t], [-t, -t], [t, -t], [-t, t], [t, t]]) raw(ctx, str, sx + dx, y + dy, o, s);
    }
    if (opts.shadow) raw(ctx, str, sx, y + (opts.shadowOff || s), opts.shadow, s);
    raw(ctx, str, sx, y, color, s);
    return w;
  }

  return { draw, width, H: GH };
})();
